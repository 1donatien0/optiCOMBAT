using System.Text;
using optiCombat.Services;

namespace optiCombat.Tests;

public sealed class FreshclamConfSupportTests : IDisposable
{
    private readonly string _root;
    private readonly List<string> _paths = new();

    public FreshclamConfSupportTests()
    {
        _root = Path.Combine(Path.GetTempPath(), "opticombat_fc_" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(_root);
    }

    public void Dispose()
    {
        foreach (var p in _paths)
        {
            try { if (File.Exists(p)) File.Delete(p); } catch { }
            try { if (File.Exists(p + ".v1.bak")) File.Delete(p + ".v1.bak"); } catch { }
        }
        try { Directory.Delete(_root, recursive: true); } catch { }
    }

    private string TempConf(string name)
    {
        var path = Path.Combine(_root, name);
        _paths.Add(path);
        return path;
    }

    [Fact]
    public void HasUtf8Bom_detects_bom_prefix()
    {
        var path = TempConf("bom.conf");
        File.WriteAllBytes(path, new byte[] { 0xEF, 0xBB, 0xBF, (byte)'#' });
        Assert.True(FreshclamConfSupport.HasUtf8Bom(path));
    }

    [Fact]
    public void IsOurManagedConf_recognizes_opticombat_marker()
    {
        Assert.True(FreshclamConfSupport.IsOurManagedConf("# freshclam.conf generated by optiCombat v6\n"));
        Assert.False(FreshclamConfSupport.IsOurManagedConf("DatabaseDirectory \"/tmp\"\n"));
    }

    [Fact]
    public void BuildConfBytes_has_no_bom_and_includes_marker()
    {
        var bytes = FreshclamConfSupport.BuildConfBytes(6, "C:/db", "C:/log/freshclam.log");
        Assert.NotNull(bytes);
        Assert.False(bytes!.Length >= 3 && bytes[0] == 0xEF);
        var text = Encoding.UTF8.GetString(bytes);
        Assert.Contains("generated by optiCombat v6", text, StringComparison.OrdinalIgnoreCase);
        Assert.Contains("DatabaseDirectory", text);
        Assert.Contains("ReceiveTimeout 0", text, StringComparison.Ordinal);
        Assert.Contains("TestDatabases no", text, StringComparison.Ordinal);
        Assert.DoesNotContain("ReceiveTimeout 30", text, StringComparison.Ordinal);
    }

    [Fact]
    public void EscapePathForConf_rejects_newlines_and_escapes_quotes()
    {
        Assert.Null(FreshclamConfSupport.EscapePathForConf("C:/db\nevil"));
        Assert.Null(FreshclamConfSupport.EscapePathForConf("C:/db\r\nevil"));
        Assert.Equal("C:/db", FreshclamConfSupport.EscapePathForConf(@"C:\db"));
        Assert.Equal("C:/say \"\"hi\"\"", FreshclamConfSupport.EscapePathForConf("C:/say \"hi\""));
    }

    [Fact]
    public void BuildConfBytes_rejects_path_with_newline()
    {
        Assert.Null(FreshclamConfSupport.BuildConfBytes(1, "C:/db\nx", "C:/log"));
        Assert.Null(FreshclamConfSupport.BuildConfBytes(1, "C:/db", "C:/log\ny"));
    }

    [Fact]
    public void BuildConfBytes_escapes_quotes_in_paths()
    {
        var text = Encoding.UTF8.GetString(FreshclamConfSupport.BuildConfBytes(1, "C:/my \"db\"", "C:/log")!);
        Assert.Contains("DatabaseDirectory \"C:/my \"\"db\"\"\"", text, StringComparison.Ordinal);
    }

    [Fact]
    public void BuildConfBytes_never_writes_obsolete_cvd_certs_directive()
    {
        var text = Encoding.UTF8.GetString(FreshclamConfSupport.BuildConfBytes(1, "C:/db", "C:/log")!);
        Assert.False(FreshclamConfSupport.ContainsObsoleteDirective(text));
        Assert.DoesNotContain("CVDCertsDirectory", text, StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void InvalidateIfLegacy_regenerates_managed_conf_with_obsolete_directive()
    {
        var path = TempConf("obsolete.conf");
        File.WriteAllText(path, "# freshclam.conf generated by optiCombat v1\nDatabaseDirectory \"C:/db\"\nCVDCertsDirectory \"C:/certs\"\n");
        FreshclamConfSupport.InvalidateIfLegacy(path);
        Assert.False(File.Exists(path));
        Assert.True(File.Exists(path + ".v1.bak"));
    }

    [Fact]
    public void InvalidateIfLegacy_keeps_clean_managed_conf()
    {
        var path = TempConf("clean.conf");
        File.WriteAllText(path, "# freshclam.conf generated by optiCombat v1\nDatabaseDirectory \"C:/db\"\n");
        FreshclamConfSupport.InvalidateIfLegacy(path);
        Assert.True(File.Exists(path));
    }

    [Fact]
    public void InvalidateIfLegacy_renames_unmanaged_conf()
    {
        var path = TempConf("legacy.conf");
        File.WriteAllText(path, "DatabaseDirectory \"/old\"\n");
        FreshclamConfSupport.InvalidateIfLegacy(path);
        Assert.False(File.Exists(path));
        Assert.True(File.Exists(path + ".v1.bak"));
    }

    [Fact]
    public void EnsureWritableConf_prefers_localappdata_path()
    {
        var preferred = TempConf("preferred.conf");
        var install = TempConf("install.conf");
        var result = FreshclamConfSupport.EnsureWritableConf(
            preferred,
            install,
            _ => FreshclamConfSupport.BuildConfBytes(1, "C:/db", "C:/log"));
        Assert.Equal(preferred, result);
        Assert.True(FreshclamConfSupport.IsOurManagedConf(File.ReadAllText(preferred)));
    }


    private static byte[] Conf(string _) => FreshclamConfSupport.BuildConfBytes(9, "C:/db", "C:/log.txt")!;

    [Fact]
    public void EnsureWritableConf_repairs_install_conf_written_with_a_bom()
    {
        var preferred = Path.Combine(_root, "local", "freshclam.conf");
        var install = Path.Combine(_root, "install", "freshclam.conf");
        Directory.CreateDirectory(Path.GetDirectoryName(install)!);
        File.WriteAllBytes(install, [0xEF, 0xBB, 0xBF, .. Conf(install)]);
        string? repaired = null;

        var used = FreshclamConfSupport.EnsureWritableConf(preferred, install, Conf, p => repaired = p);

        Assert.Equal(preferred, used);
        Assert.Equal(install, repaired);
        Assert.False(FreshclamConfSupport.HasUtf8Bom(install));
    }

    [Fact]
    public void Bom_conf_that_cannot_be_regenerated_is_set_aside()
    {
        var preferred = Path.Combine(_root, "local2", "freshclam.conf");
        var install = Path.Combine(_root, "install2", "freshclam.conf");
        Directory.CreateDirectory(Path.GetDirectoryName(install)!);
        File.WriteAllBytes(install, [0xEF, 0xBB, 0xBF, .. Conf(install)]);

        // Contenu introuvable pour le chemin d'installation : la conf BOM est mise de côté.
        var used = FreshclamConfSupport.EnsureWritableConf(
            preferred, install, p => p == preferred ? Conf(p) : null);

        Assert.Equal(preferred, used);
        Assert.False(File.Exists(install));
        Assert.True(File.Exists(install + ".bom-corrupt.bak"));
    }

    [Fact]
    public void EnsureWritableConf_falls_back_to_install_path_when_preferred_is_unusable()
    {
        var blocker = Path.Combine(_root, "blocker");
        File.WriteAllText(blocker, "fichier");
        var preferred = Path.Combine(blocker, "freshclam.conf");
        var install = Path.Combine(_root, "install3", "freshclam.conf");

        Assert.Equal(install, FreshclamConfSupport.EnsureWritableConf(preferred, install, Conf));
        Assert.Null(FreshclamConfSupport.EnsureWritableConf(preferred, install, _ => null));
    }

    [Fact]
    public void TryWriteConfAt_refuses_content_starting_with_a_bom()
    {
        var target = Path.Combine(_root, "bom", "freshclam.conf");
        Assert.Null(FreshclamConfSupport.TryWriteConfAt(target, [0xEF, 0xBB, 0xBF, (byte)'x']));
        Assert.False(File.Exists(target));
    }

    [Fact]
    public void InvalidateIfLegacy_replaces_an_existing_backup()
    {
        var conf = Path.Combine(_root, "legacy.conf");
        File.WriteAllText(conf, "DatabaseDirectory C:/old");
        File.WriteAllText(conf + ".v1.bak", "ancienne sauvegarde");

        FreshclamConfSupport.InvalidateIfLegacy(conf);
        FreshclamConfSupport.InvalidateIfLegacy(Path.Combine(_root, "absent.conf"));

        Assert.False(File.Exists(conf));
        Assert.Equal("DatabaseDirectory C:/old", File.ReadAllText(conf + ".v1.bak"));
        Assert.False(FreshclamConfSupport.HasUtf8Bom(Path.Combine(_root, "absent.conf")));
    }
}
